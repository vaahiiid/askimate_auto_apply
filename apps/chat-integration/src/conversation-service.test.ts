describeIfDatabase("a secure step blocks the composer, from the LOG", () => {
  it("blocks a page that was already open when the step was written", async () => {
    const conversation = await newConversation();
    const page = await chatPage(conversation);

    // Written the way the Secure Interaction Service writes it: through the
    // internal append route, over HTTP, with a service credential. Not injected
    // into the page — the browser is an observer of this, never its author.
    const appended = await fetch(
      `${BASE}/internal/v1/conversations/${conversation}/events`,
      {
        method: "POST",
        headers: { "Content-Type": "application/json", "x-service-cert": SERVICE_CERT },
        body: JSON.stringify({
          kind: "secret_requested",
          requestId: `sr_${"c".repeat(32)}`,
          channel: "secure_control",
          expiresAt: new Date(NOW.getTime() + 300_000).toISOString(),
        }),
      },
    );
    expect(appended.status).toBe(201);

    // It reaches the page over the stream, and the composer closes — on the
    // strength of an event the page did not write and could not have invented.
    await expect
      .poll(async () => await page.locator("#chat-send").isDisabled(), { timeout: 15_000 })
      .toBe(true);
    // Typing is never blocked. A student who is mid-sentence keeps their words;
    // only sending is inert.
    expect(await page.locator("#chat-input").isDisabled()).toBe(false);
    await page.close();
  }, 60_000);

  it("REFUSES a stale client's message even though the client thinks it may send", async () => {
    // ═════════════════════════════════════════════════════════════════════
    // Vahid, 2026-08-28: *"A failed lifecycle push must fail closed: the
    // Conversation Service must not release the composer merely because the
    // browser believes the secure step settled."*
    // ═════════════════════════════════════════════════════════════════════
    //
    // The page here is the worst case: it holds no knowledge of the open step
    // at all, because the step was written BEFORE it loaded and its stream was
    // then severed from the transcript by loading a different conversation's
    // view of the world. What stops the message is the server reading its own
    // log — not anything the browser believes.
    const conversation = await newConversation();
    const requestId = `sr_${"d".repeat(32)}`;
    await fetch(`${BASE}/internal/v1/conversations/${conversation}/events`, {
      method: "POST",
      headers: { "Content-Type": "application/json", "x-service-cert": SERVICE_CERT },
      body: JSON.stringify({
        kind: "secret_requested",
        requestId,
        channel: "secure_control",
        expiresAt: new Date(NOW.getTime() + 300_000).toISOString(),
      }),
    });

    const page = await chatPage(conversation);
    // A direct POST from the page's own context, bypassing the composer's
    // guard entirely — which is what a stale client, a broken script or a
    // hostile one would do.
    const refused = await page.evaluate(async (id) => {
      const response = await fetch(`/v1/conversations/${id}/messages`, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          "Idempotency-Key": "a-stale-client-idempotency-key",
        },
        body: JSON.stringify({ content: "PASSWORD-TYPED-INTO-THE-WRONG-BOX" }),
      });
      return { status: response.status, body: await response.text() };
    }, conversation);

    expect(refused.status).toBe(409);
    // Nothing from the body is echoed. An echo is how a refused password
    // reaches a client-side log.
    expect(refused.body).not.toContain("PASSWORD-TYPED-INTO-THE-WRONG-BOX");
    expect(refused.body).toContain("secret_request_open");

    // And nothing was written, in the database itself.
    const bodies = await pool.query<{ n: string }>(
      "SELECT count(*) AS n FROM message_bodies WHERE content LIKE $1",
      ["%PASSWORD-TYPED-INTO-THE-WRONG-BOX%"],
    );
    expect(Number(bodies.rows[0]!.n)).toBe(0);
    await page.close();
  }, 60_000);

  it("releases only when the LOG says the step settled", async () => {
    const conversation = await newConversation();
    const requestId = `sr_${"e".repeat(32)}`;
    const internal = async (body: Record<string, unknown>): Promise<number> =>
      (
        await fetch(`${BASE}/internal/v1/conversations/${conversation}/events`, {
          method: "POST",
          headers: { "Content-Type": "application/json", "x-service-cert": SERVICE_CERT },
          body: JSON.stringify(body),
        })
      ).status;

    await internal({
      kind: "secret_requested",
      requestId,
      channel: "secure_control",
      expiresAt: new Date(NOW.getTime() + 300_000).toISOString(),
    });
    const page = await chatPage(conversation);
    await expect
      .poll(async () => await page.locator("#chat-send").isDisabled(), { timeout: 15_000 })
      .toBe(true);

    // A REJECTION settles nothing — the student may retry, and the guard holds.
    await internal({ kind: "secret_rejected", requestId, reason: "confirmation_mismatch" });
    await page.waitForTimeout(800);
    expect(
      await page.locator("#chat-send").isDisabled(),
      "a rejection released the composer",
    ).toBe(true);

    // A cancellation does settle it, and the page learns from the stream.
    await internal({ kind: "secret_cancelled", requestId });
    await expect
      .poll(async () => await page.locator("#chat-send").isDisabled(), { timeout: 15_000 })
      .toBe(false);

    await sendFromComposer(page, "free again");
    await expect
      .poll(async () => (await durableOf(page)).length, { timeout: 10_000 })
      .toBe(4);
    await page.close();
  }, 90_000);
});

