describeIfDatabase("the React client on the real Conversation Service", () => {
  it("loads an existing conversation, with the SERVER's ordinals", async () => {
    // Written before the page exists, straight into the log. What the browser
    // renders is therefore the service's transcript, not one it was handed.
    const conversation = await newConversation();
    await store.append({
      conversationId: conversation,
      event: { kind: "message", actor: "student", content: "what documents do I need?" },
    });
    await store.append({
      conversationId: conversation,
      event: { kind: "message", actor: "assistant", content: "your passport, to start" },
    });

    const page = await chatPage(conversation);
    await expect
      .poll(async () => (await durableOf(page)).length, { timeout: 10_000 })
      .toBe(2);

    const durable = await durableOf(page);
    expect(durable.map((event) => event.ordinal)).toEqual([1, 2]);
    expect(durable.map((event) => event.content)).toEqual([
      "what documents do I need?",
      "your passport, to start",
    ]);
    // And it is on screen, in order.
    expect(
      await page.locator('[data-testid="turn"]').allTextContents(),
    ).toEqual(["what documents do I need?", "your passport, to start"]);
    await page.close();
  }, 60_000);

  it("sends through the service and adopts the ordinal it is given", async () => {
    const conversation = await newConversation();
    // Two events already in the log, so a client computing `length + 1` would
    // say 1 where the server says 3. The numbers must not agree by accident.
    await store.append({
      conversationId: conversation,
      event: { kind: "message", actor: "assistant", content: "hello" },
    });
    await store.append({
      conversationId: conversation,
      event: { kind: "message", actor: "assistant", content: "still here" },
    });

    const page = await chatPage(conversation);
    await sendFromComposer(page, "and about the deposit?");

    await expect
      .poll(async () => (await durableOf(page)).length, { timeout: 10_000 })
      .toBe(3);
    const durable = await durableOf(page);
    expect(durable.map((event) => event.ordinal)).toEqual([1, 2, 3]);
    expect(durable[2]?.content).toBe("and about the deposit?");

    // The database agrees, which is the half a client cannot fake.
    const stored = await store.since(conversation, 0);
    expect(stored.map((event) => event.ordinal)).toEqual([1, 2, 3]);
    await page.close();
  }, 60_000);

  it("leaves NO provisional entry once the durable event arrives", async () => {
    const conversation = await newConversation();
    const page = await chatPage(conversation);
    await sendFromComposer(page, "does the echo survive?");

    await expect
      .poll(async () => (await durableOf(page)).length, { timeout: 10_000 })
      .toBe(1);
    // One thing on screen, not two: the echo was retired by the event that
    // superseded it. Polled rather than asserted once, because a duplicate
    // could appear a moment later when the stream delivers the same event.
    await expect
      .poll(async () => await page.locator('[data-testid="turn"]').count(), { timeout: 5_000 })
      .toBe(1);
    expect(await allOf(page)).toHaveLength(1);
    await page.close();
  }, 60_000);

  it("does not duplicate an event that arrives by BOTH response and stream", async () => {
    // The send response carries the written event, and the stream delivers the
    // same event moments later. Both paths admit it; `admitDurable` ignores an
    // ordinal it already holds, so the transcript holds one copy.
    const conversation = await newConversation();
    const page = await chatPage(conversation);

    await sendFromComposer(page, "exactly once please");
    await expect
      .poll(async () => (await durableOf(page)).length, { timeout: 10_000 })
      .toBe(1);

    // Wait past a poll interval and a stream delivery, then look again. A
    // duplicate that appears late is still a duplicate, and asserting
    // immediately would miss it.
    await page.waitForTimeout(1_200);
    const durable = await durableOf(page);
    expect(durable, JSON.stringify(durable)).toHaveLength(1);
    expect(durable[0]?.ordinal).toBe(1);
    await page.close();
  }, 60_000);

  it("refuses another student's conversation, and renders nothing of it", async () => {
    const theirs = await newConversation(otherStudentId);
    await store.append({
      conversationId: theirs,
      event: { kind: "message", actor: "student", content: "PRIVATE-TO-THE-OTHER-STUDENT" },
    });

    const page = await chatPage(theirs, studentId);
    await page.waitForTimeout(1_000);
    expect(await durableOf(page)).toEqual([]);
    expect(await page.content()).not.toContain("PRIVATE-TO-THE-OTHER-STUDENT");
    await page.close();
  }, 60_000);

  it("streams without a bearer token anywhere — the cookie is the credential", async () => {
    const conversation = await newConversation();
    const urls: string[] = [];
    const page = await chatPage(conversation);
    page.on("request", (request) => urls.push(request.url()));

    await sendFromComposer(page, "watch the wire");
    await expect
      .poll(async () => (await durableOf(page)).length, { timeout: 10_000 })
      .toBe(1);

    // No credential in any URL. ADR-0033's reason for the cookie is that
    // EventSource takes no headers, and the alternative — a token in the query
    // string — reaches the access log, the Referer and the browser history.
    for (const url of urls) {
      expect(url, url).not.toMatch(/token|session|bearer|authorization/i);
    }
    // And the cookie really is HttpOnly: script cannot read it.
    expect(await page.evaluate(() => document.cookie)).not.toContain("aas-session");
    await page.close();
  }, 60_000);
});

