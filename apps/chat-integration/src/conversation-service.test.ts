const PORT = 4839;
const BASE = `http://127.0.0.1:${String(PORT)}`;
const SESSION_SECRET = "conversation-plane-session-secret-for-tests";
/** The mTLS stand-in the internal append route accepts. */
const SERVICE_CERT = "secure-service";
const NOW = new Date("2026-08-28T10:00:00Z");

const HAVE_DATABASE = await databaseReachable();
if (!HAVE_DATABASE) announceSkip("apps/chat-integration/src/conversation-service.test.ts");
const describeIfDatabase = HAVE_DATABASE ? describe : describe.skip;

let pool: pg.Pool;
let store: ConversationEventStore;
let server: Server;
let browser: Browser;
let clientDir: string;
let studentId: string;
let otherStudentId: string;

/**
 * A fresh conversation owned by `owner`.
 *
 * The id is supplied, not generated by the database: `conversations.id` is a
 * ULID with a CHECK constraint carrying the exact pattern the contract
 * publishes, so the column will not hold a value the contract forbids. A test
 * that let PostgreSQL invent one would be testing a different id space.
 */
let counter = 0;

/**
 * What the SERVER received on the `Last-Event-ID` header of every `/stream`
 * request, oldest first. `null` means the request carried no such header.
 *
 * The server, not the browser-side listener, because the server is the only
 * observer that cannot be wrong about this. Playwright's `request.headers()`
 * is a snapshot of the request as the page issued it and documents itself as
 * incomplete — `allHeaders()` exists precisely because some headers are added
 * below it. `Last-Event-ID` is one the browser adds on its own. Asserting on
 * the client-side snapshot is asserting about the instrument; asserting on
 * what arrived at the service is asserting about the guarantee, which is what
 * ADR-0035 actually promises: a reconnect resumes from the header, and the
 * service honours it.
 */
interface StreamObservation {
  /** `Last-Event-ID` as the SERVICE received it, or `null` if absent. */
  readonly resumeFrom: string | null;
  /** The ordinals the service wrote back on THIS connection, in order. */
  readonly delivered: number[];
}

const streamObservations: StreamObservation[] = [];

/** Just the resume cursors, oldest first — the common case. */
const resumeCursors = (): (string | null)[] =>
  streamObservations.map((observation) => observation.resumeFrom);
async function newConversation(owner: string = studentId): Promise<string> {
  counter += 1;
  const id = `01JBXQ8Z9WKTQ6M4H2NPB${String(counter).padStart(5, "0")}`;
  await pool.query("INSERT INTO conversations (id, student_id) VALUES ($1, $2)", [id, owner]);
  return id;
}

/**
 * A logged-in page on a conversation.
 *
 * The session is a real `__Host-` cookie, set by the browser from a real
 * `Set-Cookie`. Not injected with `addCookies`: `__Host-` has browser-enforced
 * rules — Secure, Path=/, no Domain — and a test that set the cookie by hand
 * would prove the page works with a cookie the browser would have refused.
 */
async function chatPage(
  conversationId: string,
  subject: string = studentId,
): Promise<Page> {
  const context = await browser.newContext();
  const page = await context.newPage();

  const response = await page.request.post(`${BASE}/dev/session`, {
    data: { subject },
    headers: { "Content-Type": "application/json" },
  });
  expect(response.status(), "the session route must mint a cookie").toBe(204);

  await page.addInitScript((id) => {
    (window as unknown as Record<string, unknown>)["__askimateDurableConversationId"] = id;
  }, conversationId);
  await page.goto(`${BASE}/index.html`);
  await page.locator('[data-testid="composer"]').waitFor({ state: "visible" });
  // The durable transcript has arrived. Asserting before this would be
  // asserting about a page that had not finished loading — and an empty
  // transcript would look like agreement.
  await page.waitForFunction(
    () => (window as unknown as { __askimateLoaded?: () => boolean }).__askimateLoaded?.() === true,
    undefined,
    { timeout: 15_000 },
  );
  return page;
}

/** The DURABLE events a page holds — the ones with server ordinals. */
async function durableOf(page: Page): Promise<{ ordinal: number; content: unknown }[]> {
  return (await page.evaluate(() =>
    (window as unknown as { __askimateDurable: () => unknown }).__askimateDurable(),
  )) as { ordinal: number; content: unknown }[];
}

/** Everything a page holds, durable and provisional. */
async function allOf(page: Page): Promise<unknown[]> {
  return (await page.evaluate(() =>
    (window as unknown as { __askimateTurns: () => unknown }).__askimateTurns(),
  )) as unknown[];
}

async function sendFromComposer(page: Page, text: string): Promise<void> {
  await page.locator("#chat-input").fill(text);
  await page.locator("#chat-send").click();
}

beforeAll(async () => {
  if (!HAVE_DATABASE) return;
  const admin = new pg.Pool({ connectionString: TEST_DATABASE_URL });
  try {
    await admin.query("DROP DATABASE IF EXISTS aas_conversation_browser WITH (FORCE)");
    await admin.query("CREATE DATABASE aas_conversation_browser");
  } finally {
    await admin.end();
  }
  const url = new URL(TEST_DATABASE_URL);
  url.pathname = "/aas_conversation_browser";
  pool = new pg.Pool({ connectionString: url.toString(), max: 16 });
  await migrate(pool, MIGRATIONS_DIR);
  store = new ConversationEventStore(pool);

  const students = await pool.query<{ id: string }>(
    `INSERT INTO students (subject, email_verified) VALUES ('oidc-browser-a', true),
                                                          ('oidc-browser-b', true) RETURNING id`,
  );
  studentId = students.rows[0]!.id;
  otherStudentId = students.rows[1]!.id;

  clientDir = await mkdtemp(join(tmpdir(), "aas-conv-client-"));
  await cp(join(import.meta.dirname, "..", "public", "index.html"), join(clientDir, "index.html"));
  await buildChatClient(join(clientDir, "chat-client.js"));

  const app = createConversationApp({
    store,
    sessionSecret: SESSION_SECRET,
    // The real ownership check, against the real table: a conversation belongs
    // to the student whose row names them. Not a stub that always agrees —
    // that would make the cross-student test below vacuous.
    authorise: async (subject, conversationId) => {
      const owned = await pool.query(
        "SELECT 1 FROM conversations WHERE id = $1 AND student_id = $2",
        [conversationId, subject],
      );
      return owned.rowCount === 1;
    },
    now: () => NOW,
    publicDir: clientDir,
    // The internal append route, so a test can write a lifecycle transition the
    // way the Secure Interaction Service does — over HTTP, with a credential —
    // rather than by reaching into the database behind the service's back.
    authoriseService: (req) => req.header("x-service-cert") === SERVICE_CERT,
    // Fast, so a test that waits for a poll does not wait for a second.
    pollIntervalMs: 150,
    heartbeatIntervalMs: 2_000,
    // Short, so the reconnect the drop test needs happens in a test's lifetime.
    // In production this is five minutes and exists so a rolling deployment can
    // drain an instance; here it is the mechanism that severs a live stream.
    maxStreamMs: 1_500,
    issueSessionFor: (req) => {
      const subject = (req.body as { subject?: unknown } | undefined)?.subject;
      return typeof subject === "string" ? subject : null;
    },
  });
  server = await new Promise<Server>((resolve) => {
    const listening = app.listen(PORT, "127.0.0.1", () => resolve(listening));
  });
  // An extra `request` listener alongside the app's own. It only reads, so it
  // cannot change what the service does, and it sees every request the service
  // sees — including the reconnects the browser makes by itself, which are the
  // ones no client-side assertion can observe reliably.
  server.on("request", (req, res) => {
    if (!(req.url ?? "").includes("/stream")) return;
    // Node types a header as `string | string[]`, because a client may send it
    // twice. The service reads it with `req.header()`, which takes the first,
    // so this observer takes the first too — an observer that disagreed with
    // the code it observes would report on a value nothing acted on.
    const raw = req.headers["last-event-id"];
    const observation: StreamObservation = {
      resumeFrom: (Array.isArray(raw) ? raw[0] : raw) ?? null,
      delivered: [],
    };
    streamObservations.push(observation);
    // Reading the frames the service writes, because "duplicates nothing"
    // asserted on the page is asserted AFTER the client deduplicates by
    // ordinal — which is exactly the "the paged load alone would produce the
    // same list" trap, one level down. A service that ignored the cursor and
    // replayed the conversation on every reconnect would leave the transcript
    // correct and this array full of repeats.
    const write = res.write.bind(res) as (...args: unknown[]) => boolean;
    res.write = ((...args: unknown[]): boolean => {
      const chunk = args[0];
      if (typeof chunk === "string") {
        for (const line of chunk.split("\n")) {
          const id = /^id: (\d+)$/.exec(line);
          if (id !== null) observation.delivered.push(Number(id[1]));
        }
      }
      return write(...args);
    }) as typeof res.write;
  });
  browser = await chromium.launch({ headless: true });
}, 180_000);

afterAll(async () => {
  if (!HAVE_DATABASE) return;
  await browser.close();
  await new Promise<void>((resolve) => server.close(() => resolve()));
  await pool.end();
  await rm(clientDir, { recursive: true, force: true });
});

